namespace JojoPuzzle.Core
{
    /// <summary>
    /// 스탠드업 타임 전용 데미지.
    ///
    ///   정사각형 하나의 데미지 = 전투력 × 칸 수 × 크기배율
    ///
    /// 크기배율은 전투력과 무관한 고정 상수다(퍼센트 정수로 보관, 100 = 1.0배).
    /// 정사각형을 이루지 못하고 남은 칸은 배율 없이 일반 매치 그대로(전투력 × 칸 수) 계산한다.
    ///
    /// 예) 전투력 150이 3×3을 만들면 150 × 9 × 2.1배 = 2,835.
    ///
    /// [2026-08-06 공식 변경] 원래 엑셀 기획은 두 단계였다 -
    ///   1) StandDamage = 전투력 × 크기데미지 / 100
    ///   2) 최종 = (전투력 × 칸 수) × StandDamage%
    /// 이러면 배율 자체가 전투력에서 파생되어 최종 데미지가 전투력의 "제곱"으로 커졌다.
    /// 실제로 Lv50 GR의 6×6이 20,412,000이 나왔는데 최고 보스 체력이 650,000이었고,
    /// 레벨 12배(150→1800) 성장에 데미지가 144배로 뛰어 레벨 곡선이 무의미해졌다.
    /// 또 전투력 100 미만(BR Lv1~4)에서는 2×2 배율이 100% 아래로 내려가, 게이지를 모아
    /// 발동한 스탠드업이 평범한 4매치보다 오히려 약해지는 역전까지 있었다.
    /// 그래서 배율을 상수로 떼어내 데미지가 전투력에 선형 비례하도록 바꿨다.
    /// 엑셀 원본은 개략적으로 작성된 것이라 이쪽에 맞추기로 사용자와 합의됨.
    /// </summary>
    public static class StandUpDamageTable
    {
        // 인덱스 = 정사각형 한 변의 칸 수. 값은 퍼센트(100 = 1.0배)로, 소수 배율을 정수로 다루기 위함.
        // 엑셀의 "크기데미지" 열 숫자를 그대로 쓰되, 이제는 전투력을 한 번 더 곱하지 않고
        // 이 값 자체가 최종 배율이다. 밸런싱은 이 5개 숫자만 만지면 된다.
        //
        // 정사각형을 이루지 못한 낱개 칸은 이 표를 쓰지 않는다 - 호출부에서 일반 매치와 똑같이
        // (전투력 × 칸 수)로 계산한다. 그래서 인덱스 0·1은 0이다.
        private static readonly int[] SizeMultiplierPercent =
        {
            0,     // 0 - 사용 안 함
            0,     // 1×1 - 정사각형이 아니므로 이 표의 대상이 아님
            130,   // 2×2 - 1.3배 (엑셀 원본은 100이었다. 1.0배면 같은 4칸을 일렬로 잇는 평타와
                   //              데미지가 완전히 같아서, 최소 크기 정사각형을 만들 동기가 아예
                   //              없었다. 평타 대비 30% 프리미엄을 줘서 "정사각형을 만든다"는
                   //              규칙이 첫 칸부터 성립하게 함.)
            210,   // 3×3 - 2.1배
            430,   // 4×4 - 4.3배
            870,   // 5×5 - 8.7배
            1750   // 6×6 - 17.5배
        };

        public const int MaxSquareSize = 6;

        /// <summary>
        /// 정사각형 한 변 길이에 해당하는 크기배율(퍼센트, 100 = 1.0배).
        /// 표에 없는 큰 크기는 가장 큰 값으로 고정한다 (보드가 6×6이라 실제로는 6을 넘을 수 없지만,
        /// 보드 크기를 키웠을 때 예외 대신 안전한 값이 나오도록).
        /// </summary>
        public static int GetSizeMultiplierPercent(int squareSize)
        {
            if (squareSize < 1)
                return 0;

            if (squareSize >= SizeMultiplierPercent.Length)
                return SizeMultiplierPercent[SizeMultiplierPercent.Length - 1];

            return SizeMultiplierPercent[squareSize];
        }

        /// <summary>
        /// 정사각형 하나의 최종 데미지 = 전투력 × <b>실효 칸 수</b> × 크기배율.
        /// 전투력에 선형 비례한다. 합산하는 쪽(BoardInputController.CalculateStandUpDamage)이
        /// 여러 정사각형을 더하므로 반환형은 long으로 둔다.
        ///
        /// 실효 칸 수는 그냥 칸 수가 아니라 칸마다의 무게(Cell.DamageWeight)를 더한 값이다 -
        /// 강화 안 된 칸은 1, 강화된 칸은 그 배율. 그래서 3×3 아홉 칸 중 넷이 1.5배 강화면
        /// 9가 아니라 5 + 4×1.5 = 11 로 계산된다.
        ///
        /// <b>강화를 칸 수 쪽에 곱하고 크기배율은 건드리지 않는 이유</b>: 크기배율은 "얼마나 큰
        /// 정사각형을 만들었는가"에 대한 보상이라 조각의 상태와 무관하다. 크기배율까지 강화로
        /// 부풀리면 강화의 가치가 정사각형 크기에 따라 제곱으로 튀어서, 6×6 하나에만 몰아주는
        /// 극단적인 밸런스가 된다(엑셀 원본 공식을 선형으로 바꾼 것과 같은 이유).
        ///
        /// 예전에는 정수 나눗셈으로 소수점을 버렸는데 지금은 반올림한다. 강화 배율이 소수라
        /// 버림을 유지하면 배율이 늘 조금씩 손해 보는 쪽으로 쏠린다. 전투력이 낮은 구간에서
        /// 1 차이가 날 수 있지만(예: 전투력 8의 2×2 → 41 대신 42) 그 밖에는 결과가 같다.
        /// </summary>
        public static long CalculateSquareDamage(int combatPower, int squareSize, float weightedCells)
        {
            double raw = combatPower * (double)weightedCells * GetSizeMultiplierPercent(squareSize) / 100.0;
            return (long)System.Math.Round(raw);
        }
    }
}
